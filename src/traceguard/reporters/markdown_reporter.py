"""Markdown traceability matrix - the artefact that goes into the review record."""

from __future__ import annotations

from datetime import UTC, datetime

from ..analyzer import compute_metrics
from ..model import ReqLevel, TraceGraph

_STATUS_OK = "PASS"
_STATUS_GAP = "GAP"


def render_markdown(graph: TraceGraph, title: str = "Requirements Traceability Matrix") -> str:
    metrics = compute_metrics(graph)
    stamp = datetime.now(UTC).strftime("%Y-%m-%d %H:%M UTC")
    out: list[str] = []

    out.append(f"# {title}")
    out.append("")
    out.append(f"Generated by TraceGuard on {stamp}.")
    out.append("")

    out.append("## 1. Summary")
    out.append("")
    out.append("| Metric | Value |")
    out.append("| --- | --- |")
    for key, value in metrics.items():
        label = key.replace("_", " ").replace(" pct", " (%)").capitalize()
        out.append(f"| {label} | {value} |")
    out.append("")

    out.append("## 2. Forward trace (SYS -> HLR -> LLR)")
    out.append("")
    out.append("| System req | High-level req | Low-level req | Title |")
    out.append("| --- | --- | --- | --- |")
    for sys_req in graph.by_level(ReqLevel.SYSTEM):
        hlrs = [graph.requirements[c] for c in sys_req.children if c in graph.requirements]
        if not hlrs:
            out.append(f"| {sys_req.id} | _none_ | _none_ | {sys_req.title} |")
        for hlr in sorted(hlrs, key=lambda r: r.id):
            llrs = [graph.requirements[c] for c in hlr.children if c in graph.requirements]
            if not llrs:
                out.append(f"| {sys_req.id} | {hlr.id} | _none_ | {hlr.title} |")
            for llr in sorted(llrs, key=lambda r: r.id):
                out.append(f"| {sys_req.id} | {hlr.id} | {llr.id} | {llr.title} |")
    orphans = [
        r
        for r in graph.requirements.values()
        if r.level is not ReqLevel.SYSTEM and not r.parents
    ]
    for orphan in sorted(orphans, key=lambda r: r.id):
        marker = "derived" if orphan.derived else "ORPHAN"
        out.append(f"| _{marker}_ | {orphan.id if orphan.level is ReqLevel.HIGH else '-'} "
                   f"| {orphan.id if orphan.level is ReqLevel.LOW else '-'} | {orphan.title} |")
    out.append("")

    out.append("## 3. Implementation and verification trace")
    out.append("")
    out.append("| Requirement | DAL | Code | Verification cases | Methods | Status |")
    out.append("| --- | --- | --- | --- | --- | --- |")
    for level in (ReqLevel.HIGH, ReqLevel.LOW):
        for req in graph.by_level(level):
            code = "<br>".join(str(ref) for ref in req.code_refs) or "-"
            cases = "<br>".join(c.case_id for c in req.test_refs) or "-"
            methods = ", ".join(sorted({c.method for c in req.test_refs})) or "-"
            needs_code = req.is_verifiable_unit
            ok = bool(req.test_refs) and (bool(req.code_refs) or not needs_code)
            status = _STATUS_OK if ok else _STATUS_GAP
            out.append(
                f"| {req.id} | {req.dal.value} | {code} | {cases} | {methods} | {status} |"
            )
    out.append("")

    out.append("## 4. Findings")
    out.append("")
    if not graph.findings:
        out.append("No findings. Every requirement is traced, implemented and verified.")
    else:
        out.append("| Severity | Rule | Requirement | Message | Location |")
        out.append("| --- | --- | --- | --- | --- |")
        for finding in sorted(graph.findings, key=lambda f: (f.severity != "error", f.rule)):
            out.append(
                f"| {finding.severity} | {finding.rule} | {finding.requirement_id or '-'} "
                f"| {finding.message} | {finding.source or '-'} |"
            )
    out.append("")

    out.append("## 5. Derived requirements")
    out.append("")
    derived = [r for r in graph.requirements.values() if r.derived]
    if not derived:
        out.append("None declared.")
    else:
        out.append("| Requirement | Rationale |")
        out.append("| --- | --- |")
        for req in sorted(derived, key=lambda r: r.id):
            out.append(f"| {req.id} | {req.rationale or '_missing_'} |")
    out.append("")

    return "\n".join(out)
